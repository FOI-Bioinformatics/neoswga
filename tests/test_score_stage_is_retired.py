"""The `score` stage prepares candidates; it no longer scores them.

Audit finding F0, decided 2026-09-05: retire the random forest from the default
pipeline and keep `step3_df.csv` as a deterministic pass-through of step 2.

The evidence that settled it. On the three GC-tier panels the gate removed 7 of
1222 candidates, 0 of 449, and 0 of 319 -- the scores cluster well above the
default `min_amp_pred` of 10.0, so it passed essentially everything. And every
step-4 consumer reads only the primer column:

    unified_optimizer.py:936        step3_df["primer"].tolist()
    dominating_set_optimizer.py:756 step3_df["primer"].tolist()
    background_aware_optimizer.py:518 step3_df["primer"].tolist()
    primer_expansion.py:699         step3_df["primer"].tolist()

So the score was computed for every candidate and then discarded before
selection. Asked directly whether it identifies good primers, taking the top
half of a pool by `amp_pred` and optimizing over it produced the WORST of five
half-pools (see `tests/test_step3_order_is_deterministic.py`).

The model itself is fit to synthetic data generated by a hand-written rule, so
it reproduces an opinion rather than measured amplification; under the default
`fast_score` the delta-G features are zeroed, making the prediction a pure
function of the primer sequence, blind to the genome and the reaction.

WHAT IS KEPT. The stage still writes `step3_df.csv`, because it is a required
intermediate that six modules read, and it still carries the step-2 measurements
and the deterministic order that `order_step3_rows` establishes. The random
forest is still reachable behind `--amp-model` for anyone who wants it; retiring
it from the default path is not the same as deleting it.
"""

import logging

import pandas as pd
import pytest

_STEP2_ROWS = [
    # primer, ratio, gini, fg_count, bg_count
    ("AAACCCGGGT", 12.0, 0.30, 40, 3),
    ("ACCCGGGTTT", 9.5, 0.30, 33, 4),
    ("AAGGCCTTAC", 7.0, 0.45, 21, 3),
    ("CACCGACGAC", 6.0, 0.45, 18, 3),
    ("TTGGCCAATG", 4.0, 0.55, 12, 3),
]


@pytest.fixture
def primed(tmp_path, monkeypatch):
    """A data_dir holding only step2_df.csv, with the pipeline pointed at it."""
    import neoswga.core.pipeline as pipeline_mod
    from neoswga.core import parameter

    pd.DataFrame(_STEP2_ROWS, columns=["primer", "ratio", "gini", "fg_count", "bg_count"]).to_csv(
        tmp_path / "step2_df.csv", index=False
    )

    monkeypatch.setattr(pipeline_mod, "_initialize", lambda: None)
    monkeypatch.setattr(pipeline_mod, "fg_prefixes", [str(tmp_path / "fg")], raising=False)
    monkeypatch.setattr(pipeline_mod, "fg_seq_lengths", [1_000_000], raising=False)
    monkeypatch.setattr(parameter, "data_dir", str(tmp_path), raising=False)
    monkeypatch.setattr(parameter, "verbose", False, raising=False)
    monkeypatch.setattr(parameter, "min_amp_pred", None, raising=False)
    monkeypatch.setattr(parameter, "use_amp_model", False, raising=False)
    return tmp_path


def _run(primed):
    import neoswga.core.pipeline as pipeline_mod

    pipeline_mod.step3(validate_prerequisites=False)
    return pd.read_csv(primed / "step3_df.csv")


# ---------------------------------------------------------------------------
# The stage no longer scores
# ---------------------------------------------------------------------------


def test_no_amplification_score_column_is_written(primed):
    """A column nothing selects on, and that measures an opinion rather than
    amplification, should not be in the file at all."""
    out = _run(primed)

    for col in ("on.target.pred", "amp_pred"):
        assert (
            col not in out.columns
        ), f"step3_df.csv still carries {col!r}; the scoring stage was retired"


def test_the_model_is_never_loaded(primed, monkeypatch):
    """The cost, not just the column. Retiring the stage must skip the work."""
    from neoswga.core import rf_preprocessing

    called = []
    monkeypatch.setattr(
        rf_preprocessing,
        "predict_new_primers",
        lambda *a, **k: called.append(1) or pd.DataFrame(),
    )
    _run(primed)

    assert not called, "the random forest was still run on the default path"


def test_every_candidate_survives(primed):
    """The gate removed 7 of 1222, 0 of 449 and 0 of 319 on the real panels.
    With no score there is nothing to gate on, and that must be explicit."""
    out = _run(primed)
    assert len(out) == len(_STEP2_ROWS)
    assert set(out["primer"]) == {r[0] for r in _STEP2_ROWS}


# ---------------------------------------------------------------------------
# What the file must still carry
# ---------------------------------------------------------------------------


def test_the_step2_measurements_are_carried_through(primed):
    """`gini` in particular: it leads the row order, and the report reads these."""
    out = _run(primed)
    for col in ("primer", "gini", "ratio", "fg_count", "bg_count"):
        assert col in out.columns, f"step3_df.csv lost {col!r} from step 2"


def test_the_order_is_deterministic_and_led_by_gini(primed):
    """`order_step3_rows` is what makes an unseeded run reproducible; the
    pass-through must not drop it."""
    out = _run(primed)
    assert out["gini"].is_monotonic_increasing
    for _gini, group in out.groupby("gini", sort=False):
        primers = group["primer"].tolist()
        assert primers == sorted(primers)


def test_running_twice_gives_the_same_file(primed):
    first = _run(primed)["primer"].tolist()
    second = _run(primed)["primer"].tolist()
    assert first == second


