def test_the_model_can_still_be_asked_for(primed, monkeypatch):
    """Retiring it from the default path is not deleting it."""
    from neoswga.core import parameter

    monkeypatch.setattr(parameter, "use_amp_model", True, raising=False)
    out = _run(primed)

    assert "on.target.pred" in out.columns, "--amp-model did not restore the score column"


