def test_the_amp_model_flag_exists_on_the_score_subparser():
    """A capability with no CLI route is this repository's recurring defect."""
    from neoswga.cli_unified import create_parser

    parser = create_parser()
    score = [a for a in parser._subparsers._group_actions][0].choices["score"]
    dests = {a.dest for a in score._actions}

    assert "amp_model" in dests, f"--amp-model is not offered: {sorted(dests)}"


def test_the_flag_routes_to_the_parameter_module(tmp_path, monkeypatch):
    """Spy on the stage rather than trust the assignment."""
    import json

    import neoswga.cli.pipeline as cli_pipeline
    import neoswga.core.pipeline as pipeline_mod
    from neoswga.core import parameter

    (tmp_path / "params.json").write_text(
        json.dumps(
            {
                "schema_version": 2,
                "fg_genomes": ["fg.fna"],
                "fg_prefixes": ["fg"],
                "bg_genomes": [],
                "bg_prefixes": [],
                "data_dir": str(tmp_path),
                "polymerase": "phi29",
                "reaction_temp": 30.0,
                "min_k": 12,
                "max_k": 12,
                "min_fg_freq": 1e-5,
                "max_bg_freq": 5e-6,
                "min_tm": 15,
                "max_tm": 45,
                "max_gini": 0.6,
                "max_primer": 500,
                "cpus": 1,
                "fg_seq_lengths": [1_000_000],
            }
        )
    )

    seen = {}
    monkeypatch.setattr(
        pipeline_mod,
        "step3",
        lambda *a, **k: seen.update(use=getattr(parameter, "use_amp_model", None)),
    )
    monkeypatch.setattr(pipeline_mod, "_initialize", lambda: None)
    monkeypatch.setattr(cli_pipeline, "setup_gpu_acceleration", lambda *a, **k: None)
    monkeypatch.setattr(cli_pipeline, "report_unimplemented_options", lambda *a, **k: None)

    class _Args:
        json_file = str(tmp_path / "params.json")
        quiet = True
        seed = None
        enable_qa = False
        amp_model = True
        min_amp_pred = None
        full_score = False
        fast_score = False

    cli_pipeline.run_step3(_Args())
    assert seen.get("use") is True, "--amp-model did not reach parameter.use_amp_model"
