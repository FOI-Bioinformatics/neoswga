def test_the_report_does_not_invent_a_uniform_quality_rating(tmp_path):
    """Before `a2a58c0` every primer rendered three stars because `amp_pred` was
    missing and fell back to 0.5. With the column now deliberately absent, the
    report must omit the rating rather than reinstate that constant."""
    (tmp_path / "step4_improved_df.csv").write_text(
        "primer,set_index,score,coverage,gini,mean_tm,optimizer\n"
        "AAACCCGGGT,0,1.0,0.9,0.4,32.1,hybrid\n"
        "ACCCGGGTTT,0,1.0,0.9,0.4,31.8,hybrid\n"
    )
    (tmp_path / "step3_df.csv").write_text(
        "primer,gini,ratio,fg_count,bg_count\nAAACCCGGGT,0.4,12.0,40,3\nACCCGGGTTT,0.4,9.5,33,4\n"
    )
    from neoswga.core.report.metrics import collect_pipeline_metrics

    metrics = collect_pipeline_metrics(str(tmp_path))
    assert metrics.primers, "the report failed to build without a score column"
    assert all(
        p.amp_pred == 0 for p in metrics.primers
    ), "a quality score was invented for primers the pipeline never scored"


def test_the_default_gate_value_is_also_quiet(primed, monkeypatch, caplog):
    """`parameter.min_amp_pred` defaults to 10.0, not None, on a real CLI run.

    Warning on that would fire on every ordinary invocation, which is how a
    useful warning becomes noise nobody reads.
    """
    from neoswga.core import parameter

    monkeypatch.setattr(parameter, "min_amp_pred", 10.0, raising=False)
    with caplog.at_level(logging.WARNING):
        _run(primed)

    assert "min_amp_pred" not in caplog.text


