def test_min_amp_pred_says_it_no_longer_applies(primed, monkeypatch, caplog):
    """This repository's recurring defect is an option that is accepted and read
    by nothing. Retiring the gate must not create another one."""
    from neoswga.core import parameter

    monkeypatch.setattr(parameter, "min_amp_pred", 15.0, raising=False)

    with caplog.at_level(logging.WARNING):
        _run(primed)

    assert (
        "min_amp_pred" in caplog.text
    ), "min_amp_pred was set to a gating value and silently did nothing; say so"


def test_the_default_threshold_is_not_warned_about(primed, monkeypatch, caplog):
    """Guard the guard: warning on the default would fire on every run."""
    from neoswga.core import parameter

    monkeypatch.setattr(parameter, "min_amp_pred", None, raising=False)
    with caplog.at_level(logging.WARNING):
        _run(primed)

    assert "min_amp_pred" not in caplog.text


